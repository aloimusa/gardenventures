function pureChecks(check) {
  check('production timing is exactly 180000/2000/10000 ms and the interaction is one tap',
    DEFAULT_ROUND_MS === 180000 && DEFAULT_HARVEST_MS === 2000 && DEFAULT_MOVE_MS === 10000
    && DEFAULT_TIMING.durationMs === 180000 && DEFAULT_TIMING.harvestDurationMs === 2000
    && DEFAULT_TIMING.moveDurationMs === 10000 && VENTURE_FORMAT === 4
    && VENTURE_TRAVEL_CONDITION === 'long_travel_10s_v1' && VENTURE_HARVEST_INTERACTION === 'single_tap_fixed_2s_v1');
  const production = timingProfileFromQuery('?venture-duration-ms=100&venture-harvest-ms=20&venture-move-ms=20&venture-seed=1');
  const profile = timingProfileFromQuery('?venture-test=1&venture-duration-ms=900&venture-harvest-ms=80&venture-move-ms=90&venture-seed=4294967295');
  check('short timing and uint32 seeds require the explicit development query; legacy seconds remain compatible',
    production.durationMs === 180000 && production.harvestDurationMs === 2000 && production.moveDurationMs === 10000
    && production.seedOverride === null && !production.testOverride && profile.durationMs === 900
    && profile.harvestDurationMs === 80 && profile.moveDurationMs === 90 && profile.seedOverride === 4294967295
    && profile.testOverride && timingProfileFromQuery('?venture-test=1', '0.4').durationMs === 400
    && timingProfileFromQuery('', '0.4').durationMs === 180000);
  check('accepted tap has a fixed 2 s due time; Move retains its RT-inclusive 10 s condition window',
    harvestReadyAt(3000) === 5000 && scheduledReadyAt(1000,1200,10000) === 11000
    && scheduledPostChoiceWait(1000,1200,10000) === 9800 && scheduledReadyAt(1000,12000,10000) === 12000
    && scheduledPostChoiceWait(1000,12000,10000) === 0);
  check('inputs and maturity use absolute round boundaries, including a result due exactly at expiry',
    inputAcceptedAt(4999,5000) && !inputAcceptedAt(5000,5000)
    && actionMaturesBeforeRoundEnd(5000,5000) && !actionMaturesBeforeRoundEnd(5001,5000));
  check('background leave_threshold is strict >20 s and open sessions are always invalid annotations',
    BACKGROUND_LEAVE_THRESHOLD_MS === 20000 && !backgroundInvalid(20000,false)
    && backgroundInvalid(20001,false) && backgroundInvalid(0,true));
  const annotation = backgroundAnnotation([{ id:'a',startedAt:0,endedAt:9000,durationMs:9000,openAtLastSession:false,ended:true },
    { id:'b',startedAt:10000,endedAt:22000,durationMs:12000,openAtLastSession:false,ended:true }]);
  check('background summaries preserve every duration and report threshold exclusion without changing game yield',
    annotation.durationMs === 21000 && annotation.invalid && annotation.reason === 'over_leave_threshold');

  for (const vector of GOLDENS) {
    const chain = occurrenceChainSeed(vector.seed, vector.occurrence);
    const actual = replayVentureRewards(chain, vector.rows.length).map(sample => [
      sample.drawIndex,sample.rngDrawIndex,sample.rngDrawCount,sample.rngStateBefore,sample.rngStateAfter,
      sample.uniformValues,sample.initialNormalValue,sample.selectedFactor,sample.previousObservedYield,sample.reward,
    ]);
    check(`independent normal/beta golden: seed ${vector.seed}, occurrence ${vector.occurrence}`,
      chain === vector.chain && JSON.stringify(actual) === JSON.stringify(vector.rows), JSON.stringify(actual));
  }
  let properties = true, repeatedPositive = false, repeatedZero = false, transitionTotal = 0;
  for (let seed = 0; seed < 500; seed++) {
    const samples = replayVentureRewards(occurrenceChainSeed(seed,seed % 3),30);
    for (const sample of samples) {
      if (!Number.isInteger(sample.reward) || sample.reward < 0 || sample.rngDrawCount !== sample.uniformValues.length) properties = false;
      if (sample.previousObservedYield === null && (sample.initialNormalValue === null || sample.selectedFactor !== null)) properties = false;
      if (sample.previousObservedYield !== null && (!(sample.selectedFactor > 0 && sample.selectedFactor < 1))) properties = false;
      if (sample.reward > 0 && sample.reward === sample.previousObservedYield) repeatedPositive = true;
      if (sample.reward === 0 && sample.previousObservedYield === 0) repeatedZero = true;
      transitionTotal++;
    }
  }
  const zeroTrail = replayVentureRewards(occurrenceChainSeed(1703,0),125);
  repeatedZero = zeroTrail.some(sample => sample.reward === 0 && sample.previousObservedYield === 0);
  check('rewards stay integer/nonnegative, can repeat and remain drawable after zero (never forced previous-1)',
    properties && repeatedPositive && repeatedZero && transitionTotal === 15000 && zeroTrail.some(sample => sample.reward === 0),
    JSON.stringify({ properties,repeatedPositive,repeatedZero }));
  const normal = [];
  for (let seed = 0; seed < 12000; seed++) normal.push(replayVentureRewards(occurrenceChainSeed(seed,0),1)[0].reward);
  const mean = normal.reduce((a,b) => a+b,0) / normal.length;
  const sd = Math.sqrt(normal.reduce((sum,value) => sum + value * value,0) / normal.length - mean * mean);
  check('rounded initial rewards implement Normal(mean 10, SD 1), not the retired uniform 8–12',
    Math.abs(mean - 10) < .05 && Math.abs(sd - 1) < .06 && normal.every(Number.isInteger),
    JSON.stringify({ mean,sd,min:Math.min(...normal),max:Math.max(...normal) }));
  const betaSamples = replayVentureRewards(occurrenceChainSeed(99,0),12001).slice(1).map(sample => sample.selectedFactor);
  const betaMean = betaSamples.reduce((a,b) => a+b,0) / betaSamples.length;
  check('fallback factors are genuinely Beta(22,3) with sample average near the exact .88 mean',
    REWARD_CONFIG.betaAlpha === 22 && REWARD_CONFIG.betaShape2 === 3 && REWARD_CONFIG.betaMean === .88
    && REWARD_CONFIG.betaParameterStatus === 'chosen_fallback_not_recovered_from_paper'
    && REWARD_CONFIG.normalMean === 10 && REWARD_CONFIG.normalSd === 1
    && Math.abs(betaMean - .88) < .005, JSON.stringify({ betaMean,n:betaSamples.length }));
  const chain = occurrenceChainSeed(424242,1), expected = replayVentureRewards(chain,8).map(sample => sample.rngStateAfter);
  occurrenceVisualSeed(424242,1); occurrenceChainSeed(424242,0); occurrenceVisualSeed(424242,99);
  check('occurrence/visual/species-free RNG namespaces cannot perturb one another or select a species factor',
    JSON.stringify(replayVentureRewards(chain,8).map(sample => sample.rngStateAfter)) === JSON.stringify(expected)
    && occurrenceChainSeed(424242,0) !== chain && occurrenceVisualSeed(424242,1) !== chain);
  check('a production 3-minute bound remains small without pruning any raw history',
    8 + Math.ceil(180000 / 2000) * 8 + Math.ceil(180000 / 10000) * 8 < 1500);
}

function localDay(offset = 0) {
  const d = new Date(); d.setDate(d.getDate() + offset);
  const pad = value => String(value).padStart(2,'0');
  return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())}`;
}

